//! 3D LUT export: bake a colour → colour function into a lookup table
//! other tools can apply (ImageMagick `-hald-clut`, ffmpeg `haldclut` /
//! `lut3d`, GIMP, Darktable, Resolve, OBS).
//!
//! Two formats over the same grid: a Hald CLUT (a PNG; `level` L gives
//! L² samples per axis in an L³ × L³ image) and an Adobe/Resolve `.cube`
//! text file (`LUT_3D_SIZE` L²).  Grid sample `i` of `n` is the 8-bit
//! value `round(i · 255 / (n − 1))`; at level 16 (256 samples) the grid
//! is every 8-bit colour, so the LUT reproduces the function exactly.
//! Cells are independent, so the build runs across threads and is
//! deterministic.

use image::RgbImage;

/// Smallest and largest Hald level accepted (16 = every 8-bit colour).
pub const LEVELS: std::ops::RangeInclusive<u32> = 2..=16;

/// Largest level offered for `.cube` (64 points per axis, about 7 MB of
/// text; level 16 would be over 400 MB).
pub const CUBE_MAX_LEVEL: u32 = 8;

/// Samples per axis for a Hald level.
pub fn samples(level: u32) -> u32 {
    level * level
}

/// The 8-bit value of grid sample `i` of `n` (`n >= 2`).
pub fn grid_value(i: u32, n: u32) -> u8 {
    ((i as f64 * 255.0 / (n - 1) as f64).round()) as u8
}

/// The input colour of LUT entry `index` (red fastest, then green, then
/// blue), the order both formats share.
pub fn grid_color(index: u32, n: u32) -> [u8; 3] {
    [
        grid_value(index % n, n),
        grid_value((index / n) % n, n),
        grid_value(index / (n * n), n),
    ]
}

/// Every LUT entry through `f`, in grid order, built across threads.
fn entries<F>(level: u32, f: &F) -> Vec<[u8; 3]>
where
    F: Fn(&[u8; 3]) -> [u8; 3] + Sync,
{
    assert!(
        LEVELS.contains(&level),
        "hald level {level} outside {LEVELS:?}"
    );
    let n = samples(level);
    let total = (n * n * n) as usize;
    let mut out = vec![[0u8; 3]; total];
    let threads = std::thread::available_parallelism().map_or(1, |t| t.get());
    let chunk = total.div_ceil(threads);
    std::thread::scope(|scope| {
        for (c, slice) in out.chunks_mut(chunk).enumerate() {
            scope.spawn(move || {
                let start = c * chunk;
                for (k, cell) in slice.iter_mut().enumerate() {
                    *cell = f(&grid_color((start + k) as u32, n));
                }
            });
        }
    });
    out
}

/// A Hald CLUT image of `level` (L³ × L³ pixels) for `f`.
pub fn hald<F>(level: u32, f: F) -> RgbImage
where
    F: Fn(&[u8; 3]) -> [u8; 3] + Sync,
{
    let side = level * level * level;
    let raw: Vec<u8> = entries(level, &f).into_iter().flatten().collect();
    RgbImage::from_raw(side, side, raw).expect("hald buffer matches its side")
}

/// An Adobe/Resolve `.cube` file (`LUT_3D_SIZE` = L²) for `f`.
pub fn cube<F>(level: u32, title: &str, f: F) -> String
where
    F: Fn(&[u8; 3]) -> [u8; 3] + Sync,
{
    let n = samples(level);
    let mut text = format!(
        "TITLE \"{}\"\n# generated by rehue\nLUT_3D_SIZE {n}\n",
        title.replace('"', "'")
    );
    for [r, g, b] in entries(level, &f) {
        text.push_str(&format!(
            "{:.6} {:.6} {:.6}\n",
            r as f64 / 255.0,
            g as f64 / 255.0,
            b as f64 / 255.0
        ));
    }
    text
}

/// Look a colour up in a Hald CLUT by its nearest grid sample (exact at
/// level 16 and for colours on the grid; tools interpolate in between).
pub fn hald_lookup(lut: &RgbImage, level: u32, rgb: &[u8; 3]) -> [u8; 3] {
    let n = samples(level);
    let idx = |v: u8| ((v as f64) * (n - 1) as f64 / 255.0).round() as u32;
    let index = idx(rgb[0]) + idx(rgb[1]) * n + idx(rgb[2]) * n * n;
    let side = lut.width();
    lut.get_pixel(index % side, index / side).0
}
